// Hero chart for /lab/spring-clock-change-road-deaths, drawn from data/dst-crashes/results.json as
// plain SVG, so the page shows it with no JavaScript. `node pipelines/dst-crashes/chart.mjs --write`
// puts the SVG and its table into the page between the chart markers; a test checks they match.
// Colours: slots 1-3 of the dataviz reference palette, checked with its validator on --cream
// (all pass; orange and aqua are under 3:1 contrast, so the chart has a legend, a dashed line for
// the standard-time states and a table view).
import { readFileSync, writeFileSync } from 'node:fs';

export const PAGE = new URL('../../src/content/lab/spring-clock-change-road-deaths.md', import.meta.url);
const RESULTS = new URL('../../data/dst-crashes/results.json', import.meta.url);
export const START = '<!-- dst-hero:start (generated by pipelines/dst-crashes/chart.mjs) -->';
export const END = '<!-- dst-hero:end -->';

const W = 360;
const H = 318;
const P = { left: 38, right: 350, top: 92, bottom: 268 };
const Y = { min: 0.8, max: 1.25 };
const DAYS = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];

export const SERIES = [
  { key: 'post', cls: 'dst-post', name: 'Observing states, 2007–2024, change in March' },
  { key: 'pre', cls: 'dst-pre', name: 'Observing states, 1996–2006, change in April' },
  { key: 'standard', cls: 'dst-std', name: 'Arizona and Hawaii, no clock change' },
];

const f2 = (x) => x.toFixed(2);
const sign = (o) => (o > 0 ? `+${o}` : o < 0 ? `−${-o}` : '0');

export function heroSvg(results) {
  const days = results.chart.post.map((d) => d.offset);
  const lo = days[0];
  const hi = days.at(-1);
  const x = (o) => P.left + ((o - lo + 0.5) / (hi - lo + 1)) * (P.right - P.left);
  const y = (v) => P.bottom - ((Math.min(Math.max(v, Y.min), Y.max) - Y.min) / (Y.max - Y.min)) * (P.bottom - P.top);
  const out = [];
  const yrs = (k) => (k === 'post' ? `${results.eras[1].nYears} years` : k === 'pre' ? `${results.eras[0].nYears} years` : `${results.standard.nYears} years`);
  out.push(`<svg class="dst-svg" viewBox="0 0 ${W} ${H}" role="img" aria-labelledby="dst-hero-title dst-hero-desc">`);
  out.push(`<title id="dst-hero-title">Fatal crashes on each day around the spring clock change, against an ordinary day of the same weekday</title>`);
  out.push(`<desc id="dst-hero-desc">In observing states fatal crashes rise above 1.0 in the work week after the change, both when the change was in April and since it moved to March. Arizona and Hawaii, which do not change their clocks, show no such rise. The table under the chart lists every value.</desc>`);
  // Legend, one row per series.
  SERIES.forEach((s, i) => {
    const ly = 14 + i * 18;
    out.push(`<line class="dst-line ${s.cls}" x1="${P.left}" x2="${P.left + 22}" y1="${ly}" y2="${ly}"/><text class="dst-legend" x="${P.left + 28}" y="${ly + 4}">${s.name}</text>`);
  });
  // Work-week band and the change line.
  out.push(`<rect class="dst-band" x="${f2(x(0.5))}" y="${P.top}" width="${f2(x(5.5) - x(0.5))}" height="${P.bottom - P.top}"/>`);
  out.push(`<text class="dst-note" x="${f2((x(0.5) + x(5.5)) / 2)}" y="${P.top - 6}" text-anchor="middle">Work week after</text>`);
  out.push(`<line class="dst-change" x1="${f2(x(0) - (x(1) - x(0)) / 2)}" x2="${f2(x(0) - (x(1) - x(0)) / 2)}" y1="${P.top}" y2="${P.bottom}"/>`);
  out.push(`<text class="dst-note" x="${f2(x(0) - (x(1) - x(0)) / 2 - 4)}" y="${P.top - 22}" text-anchor="end">Clocks change</text>`);
  // Grid and y labels.
  for (const v of [0.8, 0.9, 1.0, 1.1, 1.2]) {
    out.push(`<line class="${v === 1 ? 'dst-base' : 'dst-grid'}" x1="${P.left}" x2="${P.right}" y1="${f2(y(v))}" y2="${f2(y(v))}"/><text class="dst-tick" x="${P.left - 6}" y="${f2(y(v) + 4)}" text-anchor="end">${v.toFixed(1)}</text>`);
  }
  for (const o of [-14, -7, 0, 7, 13]) out.push(`<text class="dst-tick" x="${f2(x(o))}" y="${P.bottom + 16}" text-anchor="middle">${sign(o)}</text>`);
  out.push(`<text class="dst-tick" x="${(P.left + P.right) / 2}" y="${H - 6}" text-anchor="middle">Days from the change Sunday (0)</text>`);
  // Lines, standard-time states first so the observing lines sit on top.
  for (const s of [...SERIES].reverse()) {
    const pts = results.chart[s.key].map((d) => `${f2(x(d.offset))},${f2(y(d.index))}`).join(' ');
    out.push(`<polyline class="dst-line ${s.cls}" points="${pts}"/>`);
  }
  // Hover targets: one per day, with every series' value.
  for (const o of days) {
    const vals = SERIES.map((s) => `${s.name}: ${f2(results.chart[s.key].find((d) => d.offset === o).index)}`).join('; ');
    out.push(`<rect class="dst-hit" x="${f2(x(o - 0.5))}" y="${P.top}" width="${f2(x(1) - x(0))}" height="${P.bottom - P.top}"><title>Day ${sign(o)} (${DAYS[((o % 7) + 7) % 7]}). ${vals}. Years: ${SERIES.map((s) => yrs(s.key)).join(', ')}.</title></rect>`);
  }
  out.push('</svg>');
  return out.join('');
}

export function heroTable(results) {
  const rows = results.chart.post.map((d, i) => {
    const c = SERIES.map((s) => `<td>${f2(results.chart[s.key][i].index)}</td>`).join('');
    return `<tr><th scope="row">${sign(d.offset)} ${DAYS[d.weekday]}</th>${c}</tr>`;
  }).join('');
  return `<details class="dst-table"><summary>Show the numbers</summary><table><thead><tr><th scope="col">Day</th><th scope="col">Observing, 2007–2024 except 2020</th><th scope="col">Observing, 1996–2006</th><th scope="col">Arizona and Hawaii</th></tr></thead><tbody>${rows}</tbody></table></details>`;
}

export function heroBlock(results) {
  return `${START}\n<figure class="dst-figure">${heroSvg(results)}${heroTable(results)}</figure>\n${END}`;
}

export function replaceBlock(page, block) {
  const a = page.indexOf(START);
  const b = page.indexOf(END);
  if (a === -1 || b === -1 || b < a) throw new Error('Chart markers not found in the page');
  return page.slice(0, a) + block + page.slice(b + END.length);
}

if (import.meta.url === `file://${process.argv[1]}` && process.argv.includes('--write')) {
  const results = JSON.parse(readFileSync(RESULTS, 'utf8'));
  writeFileSync(PAGE, replaceBlock(readFileSync(PAGE, 'utf8'), heroBlock(results)));
  console.log('Chart written into', PAGE.pathname);
}
