// Synthetic invoice ledger for the live "Ask the Ledger" Worker.
// Invented company, invented vendors, whole AED. A fixed seed gives the same rows every run.

import { makeRng } from '../../src/lib/artifacts/prng.mjs';
import { SCHEMA_SQL } from '../../worker/ledger-api/src/schema.mjs';

export const SEED = 2028;
export const COST_CENTRES = ['Finance', 'IT', 'Operations', 'Marketing', 'People', 'Facilities', 'Procurement', 'Customer Support'];
export const ACCOUNTS = ['Software', 'Contractors', 'Travel', 'Office supplies', 'Utilities', 'Marketing spend', 'Maintenance', 'Training'];
export const VENDORS = [
  ['Brightwave Supplies', 'Office'], ['Cedarline Software', 'Software'], ['Dunmore Facilities', 'Facilities'],
  ['Eastgate Travel', 'Travel'], ['Fairlight Media', 'Marketing'], ['Granite Utilities', 'Utilities'],
  ['Hollin Consulting', 'Contractors'], ['Ironbridge IT', 'Software'], ['Juniper Print', 'Marketing'],
  ['Kestrel Maintenance', 'Facilities'], ['Larchmont Learning', 'Training'], ['Marlow Staffing', 'Contractors'],
  ['Northfield Cloud', 'Software'], ['Oakhurst Office', 'Office'], ['Pinecrest Events', 'Marketing'],
  ['Quarry Power', 'Utilities'], ['Redwater Logistics', 'Travel'], ['Silverlake Analytics', 'Software'],
  ['Thornbury Repairs', 'Facilities'], ['Upland Training', 'Training'],
];
export const FIRST_DATE = '2026-01-01';
export const LAST_DATE = '2026-09-30';
export const INVOICE_COUNT = 420;

const day = (iso, plus) => new Date(Date.parse(iso + 'T00:00:00Z') + plus * 86400000).toISOString().slice(0, 10);

export function buildDataset({ seed = SEED } = {}) {
  const rng = makeRng(seed);
  const span = (Date.parse(LAST_DATE) - Date.parse(FIRST_DATE)) / 86400000;
  const invoices = [];
  for (let i = 1; i <= INVOICE_COUNT; i++) {
    const invoice_date = day(FIRST_DATE, rng.int(0, span));
    const due_date = day(invoice_date, 30);
    // Older invoices are mostly paid; a few stay unpaid and become overdue once past their due date.
    const unpaid = rng.chance(invoice_date < '2026-07-01' ? 0.08 : 0.55);
    const status = !unpaid ? 'paid' : due_date < '2026-10-01' ? 'overdue' : 'open';
    const amount_aed = Math.round(200 + Math.pow(rng.next(), 2.2) * 24800);
    invoices.push({
      invoice_id: i,
      vendor_id: rng.int(1, VENDORS.length),
      cost_centre_id: rng.int(1, COST_CENTRES.length),
      account_id: rng.int(1, ACCOUNTS.length),
      invoice_date,
      due_date,
      amount_aed,
      status,
    });
  }
  invoices.sort((a, b) => (a.invoice_date < b.invoice_date ? -1 : a.invoice_date > b.invoice_date ? 1 : a.invoice_id - b.invoice_id));
  invoices.forEach((r, i) => (r.invoice_id = i + 1));
  return {
    cost_centres: COST_CENTRES.map((name, i) => ({ cost_centre_id: i + 1, name })),
    accounts: ACCOUNTS.map((name, i) => ({ account_id: i + 1, name })),
    vendors: VENDORS.map(([name, category], i) => ({ vendor_id: i + 1, name, category })),
    invoices,
  };
}

const q = (v) => (typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);

/** INSERT statements, 25 rows each, small enough for the D1 console. */
export function seedSql(data) {
  const out = ['-- Synthetic data only. Generated by pipelines/ledger-api/build.mjs (seed ' + SEED + '). Do not edit by hand.'];
  for (const [table, rows] of Object.entries(data)) {
    const cols = Object.keys(rows[0]);
    for (let i = 0; i < rows.length; i += 25) {
      const chunk = rows.slice(i, i + 25).map((r) => '(' + cols.map((c) => q(r[c])).join(', ') + ')');
      out.push(`INSERT INTO ${table} (${cols.join(', ')}) VALUES\n${chunk.join(',\n')};`);
    }
  }
  return out.join('\n') + '\n';
}

export { SCHEMA_SQL };
