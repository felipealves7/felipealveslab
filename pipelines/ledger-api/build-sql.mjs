// Writes schema.sql and seed.sql for the D1 database `ledger` from the seeded synthetic ledger.
// Run: node pipelines/ledger-api/build-sql.mjs   (a test checks the files match a fresh run)

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildLedger } from '../ask-the-ledger/ledger.mjs';

export const SCHEMA_SQL = `-- Synthetic ledger. Every company, account and amount is invented. Amounts are thousands of AED.
DROP TABLE IF EXISTS ledger;
CREATE TABLE ledger (
  entity TEXT NOT NULL,         -- invented company, e.g. 'North Hub'
  month TEXT NOT NULL,          -- 'YYYY-MM', 2025-01 to 2026-09
  account TEXT NOT NULL,        -- e.g. 'Product sales', 'Payroll'
  account_group TEXT NOT NULL,  -- 'Revenue', 'Cost of sales' or 'Operating expense'
  amount INTEGER NOT NULL       -- thousands of AED, always positive
);
`;

export function buildSeedSql(rows = buildLedger()) {
  const q = (s) => `'${s.replaceAll("'", "''")}'`;
  const lines = [];
  for (let i = 0; i < rows.length; i += 100) {
    const values = rows.slice(i, i + 100).map((r) => `(${q(r.entity)},${q(r.month)},${q(r.account)},${q(r.group)},${r.amount})`);
    lines.push(`INSERT INTO ledger (entity, month, account, account_group, amount) VALUES\n${values.join(',\n')};`);
  }
  return `-- Synthetic data, seed 2027. Generated by pipelines/ledger-api/build-sql.mjs.\n${lines.join('\n')}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dir = dirname(fileURLToPath(import.meta.url));
  writeFileSync(join(dir, 'schema.sql'), SCHEMA_SQL);
  writeFileSync(join(dir, 'seed.sql'), buildSeedSql());
  console.log('wrote schema.sql and seed.sql');
}
