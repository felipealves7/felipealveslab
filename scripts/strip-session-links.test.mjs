import { test } from 'node:test';
import assert from 'node:assert/strict';
import { hasSessionLink, stripSessionLinks, targetFor } from './strip-session-links.mjs';

// Synthetic session references, built from parts so this file holds no real or whole link.
const ID = 'session_' + '01' + 'Abc123Def456Ghi789';
const URL = 'https://claude.ai/code/' + ID;

test('drops the session link Claude Code appends to a pull request', () => {
  const body = `## What this changes\nA fix.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\n${URL}`;
  assert.equal(stripSessionLinks(body), '## What this changes\nA fix.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)');
});

test('keeps the label of a markdown link to a session', () => {
  assert.equal(stripSessionLinks(`Done.\n\n---\n_Generated by [Claude Code](${URL})_`), 'Done.\n\n---\n_Generated by Claude Code_');
});

test('removes a footer rule left with nothing under it', () => {
  assert.equal(stripSessionLinks(`Done.\n\n---\n${URL}\n`), 'Done.');
});

test('drops Claude-Session lines and keeps other trailers', () => {
  const msg = `Fix parser\n\nCo-Authored-By: Claude <noreply@anthropic.com>\nClaude-Session: ${URL}`;
  assert.equal(stripSessionLinks(msg), 'Fix parser\n\nCo-Authored-By: Claude <noreply@anthropic.com>');
});

test('replaces a link or id inside a sentence and keeps the sentence', () => {
  assert.equal(stripSessionLinks(`The body ends with \`${URL}\` here.`), 'The body ends with `[session link removed]` here.');
  assert.equal(stripSessionLinks(`See ${ID} for details.`), 'See [session link removed] for details.');
});

test('replaces a shortened link quoted in a review', () => {
  const quoted = 'ends with `claude.ai/code/' + 'session_…` link';
  assert.equal(stripSessionLinks(quoted), 'ends with `[session link removed]` link');
});

test('handles Windows line endings', () => {
  assert.equal(stripSessionLinks(`a\r\n${URL}\r\n`), 'a');
});

test('leaves text without a session link unchanged, including the generic footer', () => {
  const body = 'Plain text.\n\n_Generated by [Claude Code](https://claude.ai/code)_\n';
  assert.equal(stripSessionLinks(body), body);
  assert.equal(hasSessionLink(body), false);
  assert.equal(hasSessionLink(`x ${URL}`), true);
  assert.equal(hasSessionLink(''), false);
  assert.equal(hasSessionLink(null), false);
});

test('maps each event to the item it should clean', () => {
  const repo = 'o/r';
  assert.deepEqual(targetFor('issues', { issue: { number: 3 } }, repo), { kind: 'issue #3', path: '/repos/o/r/issues/3', method: 'PATCH' });
  assert.equal(targetFor('pull_request', { pull_request: { number: 7 } }, repo).path, '/repos/o/r/pulls/7');
  assert.equal(targetFor('issue_comment', { issue: { number: 7 }, comment: { id: 99 } }, repo).path, '/repos/o/r/issues/comments/99');
  assert.equal(targetFor('pull_request_review_comment', { comment: { id: 5 } }, repo).path, '/repos/o/r/pulls/comments/5');
  const review = targetFor('pull_request_review', { pull_request: { number: 7 }, review: { id: 8 } }, repo);
  assert.deepEqual([review.path, review.method], ['/repos/o/r/pulls/7/reviews/8', 'PUT']);
});

test('ignores unknown events and malformed ids', () => {
  assert.equal(targetFor('push', {}, 'o/r'), null);
  assert.equal(targetFor('issues', { issue: { number: '3/../x' } }, 'o/r'), null);
  assert.equal(targetFor('issue_comment', { comment: { id: -1 } }, 'o/r'), null);
});
